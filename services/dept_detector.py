DEPT_RULES = [
    {
        'dept': 'ДСГД',
        'keys': [
            'язык', 'история',
            'социолог', 'политолог', 'культуролог', 'экологи',
            'безопасност', 'право человека',
        ]
    },
    {
        'dept': 'ДМИС',
        'keys': [
            'экономик', 'предпринимател', 'информационно-коммуникацион',
            'икт', 'правов', ' право', 'педагог', 'психолог',
            'возрастн', 'искусственный интеллект', 'наука об образовани',
            'введение в педагог',
        ]
    },
    {
        'dept': 'ДСОК',
        'keys': [
            'спорт', 'физкультур', 'атлетик', 'подвижные',
            'анатоми', 'физичес упражн', 'коучинг', 'игры',
            'функциональн',
        ]
    },
]

def detect_dept(disc_name: str) -> str:
    """Return dept code or 'unmatched'."""
    low = disc_name.lower()
    for rule in DEPT_RULES:
        if any(k.lower() in low for k in rule['keys']):
            return rule['dept']
    return 'unmatched'